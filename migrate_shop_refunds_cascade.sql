-- ============================================================
--  shop_refunds.order_id — RESTRICT to CASCADE  (defect M16)
--  tmp/shop/remedy.md, Phase 2
-- ============================================================
--
--  THE PROBLEM
--    shop_refunds.order_id is ON DELETE RESTRICT while every other child of
--    shop_orders cascades:
--
--      shop_order_items    ON DELETE CASCADE
--      shop_order_events   ON DELETE CASCADE
--      shop_shipments      ON DELETE CASCADE
--      shop_payment_proofs ON DELETE CASCADE
--      shop_refunds        ON DELETE RESTRICT   <-- outlier
--
--    Consequence: once a refund row exists the parent order can never be
--    deleted, so cleanup tooling and admin data requests fail with
--    "Cannot delete or update a parent row: a foreign key constraint fails"
--    (MySQL 1451). Every other order deletes cleanly.
--
--  THE DECISION
--    CASCADE, for consistency with the other four children.
--
--    The counter-argument is that a refund is a financial record and arguably
--    should not disappear with its order. That is outweighed here by three
--    things:
--      1. shop_refunds keeps its own ledger_ref_id and receipt_ref, and the
--         money itself moved through ewallet_ledger, which is never cascaded.
--      2. The order is the sole context for a refund row; an orphaned refund
--         would dangle with no member_id to attribute it to.
--      3. Four of five siblings already cascade, so RESTRICT was the anomaly,
--         not the design.
--
--    If the business later wants refunds to outlive orders, that is a policy
--    change: keep RESTRICT and instead give orders a soft-delete status. Do not
--    re-add RESTRICT here — it will silently break cleanup again.
--
--  SAFE TO RE-RUN: the information_schema guard makes it a no-op once applied.
-- ============================================================

-- The constraint name is auto-generated by MySQL (shop_refunds_ibfk_1 on a
-- fresh install), so resolve it rather than hardcoding a name that may differ
-- on a database that predates or postdates this file.
--
-- The replacement is added WITHOUT an explicit name on purpose: MySQL refuses to
-- reuse a constraint name inside the same ALTER ("Duplicate foreign key
-- constraint name"), and the old name is still held at parse time by the DROP.
-- Letting MySQL generate the successor keeps this idempotent.
SET @fk_name = (
    SELECT k.CONSTRAINT_NAME
      FROM information_schema.KEY_COLUMN_USAGE k
     WHERE k.CONSTRAINT_SCHEMA = DATABASE()
       AND k.TABLE_NAME        = 'shop_refunds'
       AND k.COLUMN_NAME       = 'order_id'
       AND k.REFERENCED_TABLE_NAME IS NOT NULL
     LIMIT 1
);

SET @current_rule = (
    SELECT rc.DELETE_RULE
      FROM information_schema.REFERENTIAL_CONSTRAINTS rc
      JOIN information_schema.KEY_COLUMN_USAGE k
        ON k.CONSTRAINT_NAME    = rc.CONSTRAINT_NAME
       AND k.CONSTRAINT_SCHEMA = rc.CONSTRAINT_SCHEMA
     WHERE rc.CONSTRAINT_SCHEMA = DATABASE()
       AND k.TABLE_NAME  = 'shop_refunds'
       AND k.COLUMN_NAME = 'order_id'
);

SET @sql = IF(
    @current_rule = 'CASCADE',
    'DO 0',
    CONCAT('ALTER TABLE shop_refunds
               DROP FOREIGN KEY `', @fk_name, '`,
               ADD FOREIGN KEY (order_id) REFERENCES shop_orders(id) ON DELETE CASCADE')
);

PREPARE stmt FROM @sql; EXECUTE stmt; DEALLOCATE PREPARE stmt;

-- Report the rule the migration finished in.
SELECT rc.DELETE_RULE AS shop_refunds_order_id_delete_rule
  FROM information_schema.REFERENTIAL_CONSTRAINTS rc
  JOIN information_schema.KEY_COLUMN_USAGE k
    ON k.CONSTRAINT_NAME    = rc.CONSTRAINT_NAME
   AND k.CONSTRAINT_SCHEMA = rc.CONSTRAINT_SCHEMA
 WHERE rc.CONSTRAINT_SCHEMA = DATABASE()
   AND k.TABLE_NAME  = 'shop_refunds'
   AND k.COLUMN_NAME = 'order_id';